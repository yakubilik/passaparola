// Writes src/voice/clips.generated.ts: one static require per clip in
// assets/voice, so Metro bundles them and the app knows which lines have a
// recording (the rest are read by expo-speech). Runs before `start` and
// `ios`; run it by hand after adding clips: `node scripts/gen-voice-index.mjs`.
import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const app = join(dirname(fileURLToPath(import.meta.url)), '..');
const keys = readdirSync(join(app, 'assets', 'voice'))
  .filter((f) => f.endsWith('.mp3'))
  .map((f) => f.slice(0, -4))
  .sort();
const body = keys.map((k) => `  ${JSON.stringify(k)}: require('../../assets/voice/${k}.mp3'),`).join('\n');
writeFileSync(
  join(app, 'src', 'voice', 'clips.generated.ts'),
  `// Generated by scripts/gen-voice-index.mjs from assets/voice. Do not edit.\n` +
    `export const CLIPS: Record<string, number> = {\n${body}\n};\n`,
);
console.log(`${keys.length} voice clips indexed`);
