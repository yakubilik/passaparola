#!/usr/bin/env python3
"""Pre-records every spoken line of the game with a neural Turkish voice.

Reads the question sets (js/questions.js) and the host lines (tools/host-lines.json),
writes assets/voice/<key>.mp3 and assets/voice/lines.js (the list the game reads).
Lines whose text did not change are not recorded again.

    python3 tools/gen-voice.py [--voice tr-TR-AhmetNeural] [--rate +8%]
"""
import argparse, concurrent.futures as cf, hashlib, json, os, subprocess, sys, time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'assets', 'voice')
EDGE = os.path.expanduser('~/.local/bin/edge-tts')


# How the letters are said out loud (a bare "B." is read unreliably).
LETTER_NAMES = {'A': 'a', 'B': 'be', 'C': 'ce', 'Ç': 'çe', 'D': 'de', 'E': 'e', 'F': 'fe', 'G': 'ge',
                'Ğ': 'yumuşak ge', 'H': 'he', 'I': 'ı', 'İ': 'i', 'J': 'je', 'K': 'ke', 'L': 'le', 'M': 'me',
                'N': 'ne', 'O': 'o', 'Ö': 'ö', 'P': 'pe', 'R': 're', 'S': 'se', 'Ş': 'şe', 'T': 'te', 'U': 'u',
                'Ü': 'ü', 'V': 've', 'Y': 'ye', 'Z': 'ze'}


def load_sets():
    js = "const q=require(process.argv[1]);process.stdout.write(JSON.stringify(q.SETS))"
    out = subprocess.check_output(['node', '-e', js, os.path.join(ROOT, 'js', 'questions.js')])
    return json.loads(out)


def lines():
    out = {}
    for si, qs in enumerate(load_sets()):
        for k, q in enumerate(qs):
            # The host reads the clue first and says the letter after it.
            name = LETTER_NAMES[q['l']]
            tail = f"{name}." if q['t'] == 'b' else f"İçinde {name}."
            out[f'q-{si}-{k}'] = f"{q['q'].rstrip('.')}... {tail}"
            # The voice service now and then returns nothing for a line; the second wording is the spare.
            out[f'a-{si}-{k}'] = [f"{q['a'][0]} olacaktı.", f"Doğru yanıt {q['a'][0]} olacaktı."]
    with open(os.path.join(ROOT, 'tools', 'host-lines.json'), encoding='utf-8') as f:
        for key, text in json.load(f).items():
            if not key.startswith('_'):
                out[key] = text
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--voice', default='tr-TR-AhmetNeural')
    ap.add_argument('--rate', default='+8%')
    args = ap.parse_args()
    os.makedirs(OUT, exist_ok=True)
    stamp_file = os.path.join(OUT, '.stamps.json')
    stamps = json.load(open(stamp_file)) if os.path.exists(stamp_file) else {}
    todo = {}
    all_lines = lines()
    for key, text in all_lines.items():
        if isinstance(text, str):
            all_lines[key] = text = [text]
        h = hashlib.sha1(f'{args.voice}|{args.rate}|{text[0]}'.encode()).hexdigest()[:12]
        if stamps.get(key) != h or not os.path.exists(os.path.join(OUT, key + '.mp3')):
            todo[key] = (text, h)

    def rec(item):
        key, (texts, h) = item
        tmp = os.path.join(OUT, key + '.tmp.mp3')
        for attempt in range(6):
            if attempt: time.sleep(attempt)
            text = texts[min(attempt // 2, len(texts) - 1)]
            r = subprocess.run([EDGE, '--voice', args.voice, f'--rate={args.rate}', '--text', text,
                                '--write-media', tmp], capture_output=True)
            if r.returncode == 0 and os.path.getsize(tmp) > 1000:
                os.replace(tmp, os.path.join(OUT, key + '.mp3'))
                return key, h, None
        if os.path.exists(tmp):
            os.remove(tmp)
        return key, h, r.stderr.decode()[-300:]

    failed = []
    with cf.ThreadPoolExecutor(3) as ex:
        for key, h, err in ex.map(rec, todo.items()):
            if err:
                failed.append((key, err))
            else:
                stamps[key] = h
    for key in list(stamps):
        if key not in all_lines:
            stamps.pop(key)
            p = os.path.join(OUT, key + '.mp3')
            if os.path.exists(p):
                os.remove(p)
    json.dump(stamps, open(stamp_file, 'w'), indent=0, sort_keys=True)
    with open(os.path.join(OUT, 'lines.js'), 'w', encoding='utf-8') as f:
        f.write('// Generated by tools/gen-voice.py. Keys with a recorded clip in assets/voice/.\n')
        f.write('(function (root) { root.PP = Object.assign(root.PP || {}, { VOICE_LINES: ')
        f.write(json.dumps({k: all_lines[k][0] for k in sorted(stamps)}, ensure_ascii=False, indent=0))
        f.write(' }); })(this);\n')
    print(f'recorded {len(todo) - len(failed)}, failed {len(failed)}, total {len(stamps)}')
    for key, err in failed:
        print('FAILED', key, err, file=sys.stderr)
    return 1 if failed else 0


if __name__ == '__main__':
    sys.exit(main())
